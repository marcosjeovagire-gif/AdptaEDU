/**
 * Consulta estruturada e inteligente de Habilidades Curriculares
 * Permite busca por Série, Componente, Bimestre e Texto (busca semântica e por sinônimos).
 * Retorna as habilidades aprovadas com rastreabilidade da página de origem no PDF.
 */
export function consultarMatriz(params: {
  anoSerie?: string;
  componente?: string;
  bimestre?: string;
  texto?: string;
}): {
  habilidades: CurriculumSkill[];
  sugestoesAderentes: CurriculumSkill[];
  matrizes: CurriculumMatrix[];
  total: number;
} {
  const { anoSerie, componente, bimestre, texto } = params;
  const textoNorm = texto ? normalizarTexto(texto) : '';
  const serieNorm = anoSerie ? normalizarTexto(anoSerie) : '';
  const compNorm = componente ? normalizarTexto(componente) : '';
  const bimNorm = bimestre ? normalizarTexto(bimestre) : '';

  // 1. Filtragem primária
  let filtradas = HABILIDADES_GERAIS_SEDUC_2026.filter(hab => {
    if (!hab.active) return false;

    // Filtro por série
    if (serieNorm) {
      const habSerieNorm = normalizarTexto(hab.grade);
      const matchSerie = habSerieNorm.includes(serieNorm) || serieNorm.includes(habSerieNorm) ||
        (serieNorm.includes('6') && habSerieNorm.includes('6')) ||
        (serieNorm.includes('7') && habSerieNorm.includes('7')) ||
        (serieNorm.includes('8') && habSerieNorm.includes('8')) ||
        (serieNorm.includes('9') && habSerieNorm.includes('9')) ||
        (serieNorm.includes('1') && habSerieNorm.includes('1')) ||
        (serieNorm.includes('2') && habSerieNorm.includes('2')) ||
        (serieNorm.includes('3') && habSerieNorm.includes('3'));
      if (!matchSerie) return false;
    }

    // Filtro por componente curricular
    if (compNorm) {
      const habCompNorm = normalizarTexto(hab.subject);
      const matchComp = habCompNorm.includes(compNorm) || compNorm.includes(habCompNorm) ||
        (compNorm.includes('portug') && habCompNorm.includes('portug')) ||
        (compNorm.includes('matemat') && habCompNorm.includes('matemat')) ||
        (compNorm.includes('cien') && habCompNorm.includes('cien')) ||
        (compNorm.includes('hist') && habCompNorm.includes('hist')) ||
        (compNorm.includes('geog') && habCompNorm.includes('geog')) ||
        (compNorm.includes('art') && habCompNorm.includes('art')) ||
        (compNorm.includes('ingl') && habCompNorm.includes('ingl')) ||
        (compNorm.includes('fisic') && habCompNorm.includes('fisic')) ||
        (compNorm.includes('quim') && habCompNorm.includes('quim')) ||
        (compNorm.includes('biol') && habCompNorm.includes('biol')) ||
        (compNorm.includes('filos') && habCompNorm.includes('filos')) ||
        (compNorm.includes('sociol') && habCompNorm.includes('sociol'));
      if (!matchComp) return false;
    }

    // Filtro por bimestre se especificado
    if (bimNorm) {
      const habBimNorm = normalizarTexto(hab.bimestre || '');
      if (habBimNorm && !habBimNorm.includes(bimNorm) && !bimNorm.includes(habBimNorm)) {
        // Se o filtro pede 3º ou 4º, verificar compatibilidade
        if (bimNorm.includes('3') && !habBimNorm.includes('3')) return false;
        if (bimNorm.includes('4') && !habBimNorm.includes('4')) return false;
      }
    }

    return true;
  });

  // Se o filtro for muito restrito e não achar nada, afrouxar apenas a série ou componente
  if (filtradas.length === 0 && compNorm) {
    filtradas = HABILIDADES_GERAIS_SEDUC_2026.filter(h => 
      normalizarTexto(h.subject).includes(compNorm) || compNorm.includes(normalizarTexto(h.subject))
    );
  }

  // 2. Ranqueamento semântico por relevância ao texto de busca
  let sugestoesAderentes: CurriculumSkill[] = [];

  if (textoNorm && filtradas.length > 0) {
    const palavrasChave = textoNorm.split(/\s+/).filter(p => p.length >= 3);

    const pontuadas = filtradas.map(hab => {
      let score = 0;
      const descNorm = normalizarTexto(hab.skillDescription);
      const objNorm = normalizarTexto(hab.knowledgeObject);
      const unidNorm = normalizarTexto(hab.thematicUnit);
      const codeNorm = normalizarTexto(hab.skillCode);

      // Match exato de código (ex: EF69LP06)
      if (codeNorm.includes(textoNorm) || textoNorm.includes(codeNorm)) {
        score += 100;
      }

      palavrasChave.forEach(palavra => {
        if (descNorm.includes(palavra)) score += 10;
        if (objNorm.includes(palavra)) score += 15;
        if (unidNorm.includes(palavra)) score += 5;
        if (codeNorm.includes(palavra)) score += 20;
      });

      return { hab, score };
    });

    pontuadas.sort((a, b) => b.score - a.score);
    sugestoesAderentes = pontuadas.slice(0, 3).map(p => p.hab);
  } else {
    // Sem texto, sugerir as primeiras habilidades da disciplina
    sugestoesAderentes = filtradas.slice(0, 3);
  }

  // Obter matrizes correspondentes
  const matrixIds = new Set(filtradas.map(h => h.matrixId));
  const matrizesRelacionadas = MATRIZES_GERAIS_SEDUC_2026.filter(m => matrixIds.has(m.id));

  return {
    habilidades: filtradas,
    sugestoesAderentes,
    matrizes: matrizesRelacionadas,
    total: filtradas.length
  };
}

