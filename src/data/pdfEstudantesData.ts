/**
 * Converte a base bruta de estudantes do PDF para a tipagem oficial Estudante do sistema.
 */
export function gerarEstudantesOficiaisDoPdf(): Estudante[] {
  const dataAtual = new Date().toISOString();

  return ESTUDANTES_PDF_RAW.map((item, index) => {
    // Código de matrícula institucional padronizado e único
    const turmaCode = item.turma.replace(/[^\w]/g, '').toUpperCase();
    const seqStr = String(index + 1).padStart(3, '0');
    const matricula = `2026-${turmaCode}-${seqStr}`;

    return {
      id: `std-pdf-${index + 1}`,
      nome: item.nome.trim(),
      matricula,
      turma: item.turma.trim(),
      anoSerie: item.anoSerie.trim(),
      turno: item.turno,
      dataNascimento: item.dataNascimento,
      situacao: item.situacao,
      professoresAutorizadosIds: [],
      profissionaisApoioIds: [],
      arquivoOrigem: 'Colégio Estadual Olynto Pereira de Castro – 2º semestre/ 2026',
      paginaDocumento: item.sourcePage,
      dataImportacao: dataAtual,
      laudo: item.laudo,
      responsaveis: item.responsaveis,
      telefones: item.telefones,
      paeResponsavelNome: item.paeResponsavelNome,
      paeResponsavelEmail: item.paeResponsavelEmail,
      statusLaudo: item.statusLaudo,
      observacoesAcessibilidade: item.laudo,
    };
  });
}

